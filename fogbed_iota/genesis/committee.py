"""Step 1 of the two-step genesis: committee preparation.

Produces a persistent, versioned *committee state* from which the genesis can be reproduced
bit-for-bit (verified: two runs of ``iota-localnet genesis --from-config`` on the same state
yield identical ``genesis.blob`` sha256):

  <state_dir>/
    committee.json        public: release pins, nodes (name, role, ip, ports, peer-id), genesis params
    genesis-config.yaml   SECRET (0600): exact input of `iota-localnet genesis --from-config`
    secrets.json          SECRET (0600): per-node key material in validator.yaml encodings
    benchmark.keystore    SECRET (0600): keys of the genesis gas accounts (funding keystore)

Key material is generated by the official v1.33.1 builder (`iota-localnet genesis
--write-config --benchmark-ips ...`), so authority keys (BLS12-381) are produced by the
reference implementation; Ed25519 gateway keys are generated here. Existing state is reused
(never silently regenerated); a different spec raises CommitteeError.
"""

from __future__ import annotations

import base64
import hashlib
import json
import logging
import os
import shutil
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

import yaml

from .errors import CommitteeError, ConfigValidationError
from .keys import (
    b64_seed,
    iota_privkey_from_seed,
    bech32_encode,
    IOTA_PRIVKEY_HRP,
    new_seed,
    peer_id_from_network_seed,
)
from .netaddr import validate_virtual_ip
from .release import IotaRelease, ensure_same_release, load_release
from .tools import ToolRunner

logger = logging.getLogger("fogbed_iota.genesis.committee")

SCHEMA_VERSION = 1
COMMITTEE_JSON = "committee.json"
GENESIS_CONFIG = "genesis-config.yaml"
SECRETS_JSON = "secrets.json"
BENCHMARK_KEYSTORE = "benchmark.keystore"
DEFAULT_SUBNET = "10.0.0.0/24"


@dataclass(frozen=True)
class Ports:
    """Per-node ports. Defaults are the standard IOTA validator/fullnode ports, which is also
    what the official deployment templates use (8080 gRPC, 8084 P2P)."""

    network: int = 8080    # tcp  validator gRPC / `network-address`
    consensus: int = 8083  # tcp  Starfish consensus (genesis `primary_address`, announced as /udp/<p>/http)
    p2p: int = 8084        # udp  anemo P2P over QUIC
    metrics: int = 9184    # tcp  Prometheus
    admin: int = 1337      # tcp  admin interface (loopback only)
    json_rpc: int = 9000   # tcp  JSON-RPC (gateway/fullnode only)
    grpc: int = 50051      # tcp  gRPC API (gateway/fullnode only)

    def shifted(self, delta: int) -> "Ports":
        return Ports(*(v + delta for v in (self.network, self.consensus, self.p2p, self.metrics, self.admin, self.json_rpc, self.grpc)))

    def as_dict(self) -> Dict[str, int]:
        return dict(network=self.network, consensus=self.consensus, p2p=self.p2p,
                    metrics=self.metrics, admin=self.admin, json_rpc=self.json_rpc, grpc=self.grpc)


@dataclass
class CommitteeSpec:
    """Input of Step 1.

    ``port_stride`` > 0 gives validator ``i`` the ports ``base + i * stride`` (for topologies
    where several nodes share one IP / network namespace). With the default 0 every node uses
    the standard ports and is isolated by its own Fogbed virtual IP.
    """

    network_name: str
    validators: List[Tuple[str, str]]               # (name, virtual ip)
    gateways: List[Tuple[str, str]] = field(default_factory=list)
    subnet: Optional[str] = DEFAULT_SUBNET
    ports: Ports = field(default_factory=Ports)
    port_stride: int = 0
    epoch_duration_ms: Optional[int] = None         # None -> builder default (no override)

    def ports_for(self, index: int) -> Ports:
        return self.ports.shifted(index * self.port_stride)

    def all_nodes(self) -> List[Tuple[str, str, str]]:
        return [(n, ip, "validator") for n, ip in self.validators] + [(n, ip, "gateway") for n, ip in self.gateways]

    def validate(self) -> None:
        if not self.network_name or "/" in self.network_name:
            raise CommitteeError(f"invalid network_name '{self.network_name}'")
        if len(self.validators) < 1:
            raise CommitteeError("at least one validator is required")
        if len(self.validators) < 4:
            logger.warning(
                "committee has %d validator(s); Starfish BFT tolerates f=(n-1)//3 faults, use >=4 for a meaningful BFT network",
                len(self.validators),
            )
        names, ips = set(), set()
        for name, ip, role in self.all_nodes():
            validate_virtual_ip(ip, self.subnet, f"{role} '{name}'")
            if name in names:
                raise CommitteeError(f"duplicate node name '{name}'")
            names.add(name)
            ips.add(ip)
        endpoints: Dict[Tuple[str, int], str] = {}
        for index, (name, ip, _role) in enumerate(self.all_nodes()):
            ports = self.ports_for(index).as_dict()
            if len(set(ports.values())) != len(ports):
                raise CommitteeError(f"node '{name}' has conflicting ports: {ports}")
            for label, port in ports.items():
                if not 1 <= port <= 65535:
                    raise CommitteeError(f"node '{name}' port {label}={port} out of range")
                owner = endpoints.setdefault((ip, port), f"{name}.{label}")
                if owner != f"{name}.{label}":
                    raise CommitteeError(
                        f"port conflict on {ip}:{port} between {owner} and {name}.{label}",
                        hint="use distinct IPs per node or set port_stride > 0",
                    )

    def fingerprint(self) -> Dict[str, Any]:
        return {
            "network_name": self.network_name,
            "validators": [list(v) for v in self.validators],
            "gateways": [list(g) for g in self.gateways],
            "ports": self.ports.as_dict(),
            "port_stride": self.port_stride,
            "epoch_duration_ms": self.epoch_duration_ms,
        }


@dataclass
class CommitteeNode:
    name: str
    role: str
    index: int
    ip: str
    ports: Dict[str, int]
    peer_id: str

    def p2p_external(self) -> str:
        return f"/ip4/{self.ip}/udp/{self.ports['p2p']}/quic"

    def network_announced(self) -> str:
        return f"/ip4/{self.ip}/tcp/{self.ports['network']}/http"

    def consensus_announced(self) -> str:
        return f"/ip4/{self.ip}/udp/{self.ports['consensus']}/http"


@dataclass
class Committee:
    state_dir: Path
    release: Dict[str, Any]
    spec: Dict[str, Any]
    nodes: List[CommitteeNode]
    genesis_parameters: Dict[str, Any]
    genesis_config_sha256: str
    created_at: str

    @property
    def validators(self) -> List[CommitteeNode]:
        return [n for n in self.nodes if n.role == "validator"]

    @property
    def gateways(self) -> List[CommitteeNode]:
        return [n for n in self.nodes if n.role == "gateway"]

    def node(self, name: str) -> CommitteeNode:
        for n in self.nodes:
            if n.name == name:
                return n
        raise CommitteeError(f"unknown node '{name}'")

    @property
    def genesis_config_path(self) -> Path:
        return self.state_dir / GENESIS_CONFIG

    def secrets(self) -> Dict[str, Dict[str, str]]:
        return json.loads((self.state_dir / SECRETS_JSON).read_text(encoding="utf-8"))

    def to_json(self) -> Dict[str, Any]:
        return {
            "schema_version": SCHEMA_VERSION,
            "release": self.release,
            "created_at": self.created_at,
            "spec": self.spec,
            "genesis_parameters": self.genesis_parameters,
            "genesis_config_file": GENESIS_CONFIG,
            "genesis_config_sha256": self.genesis_config_sha256,
            "nodes": [
                {"name": n.name, "role": n.role, "index": n.index, "ip": n.ip, "ports": n.ports, "peer_id": n.peer_id,
                 "announced": {"p2p": n.p2p_external(), "network": n.network_announced(),
                               "consensus": n.consensus_announced()}}
                for n in self.nodes
            ],
        }


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _write_secret(path: Path, data: bytes) -> None:
    fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as handle:
        handle.write(data)
    os.chmod(str(path), 0o600)


def load_committee(state_dir: Path, release: Optional[IotaRelease] = None) -> Committee:
    """Load + integrity-check persisted committee state (release pin, config checksum)."""
    state_dir = Path(state_dir)
    path = state_dir / COMMITTEE_JSON
    if not path.is_file():
        raise CommitteeError(f"no committee state at {path}", hint="run Step 1 first (`python -m fogbed_iota.genesis prepare ...`)")
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("schema_version") != SCHEMA_VERSION:
        raise CommitteeError(f"{path}: unsupported schema_version {data.get('schema_version')}")
    ensure_same_release(data["release"], f"committee state {path}", release)
    cfg = state_dir / GENESIS_CONFIG
    if not cfg.is_file() or _sha256_bytes(cfg.read_bytes()) != data["genesis_config_sha256"]:
        raise CommitteeError(
            f"{cfg} is missing or does not match the checksum recorded in committee.json",
            hint="the committee state was modified after Step 1; regenerate with --force",
        )
    nodes = [CommitteeNode(n["name"], n["role"], n["index"], n["ip"], n["ports"], n["peer_id"]) for n in data["nodes"]]
    return Committee(state_dir, data["release"], data["spec"], nodes, data["genesis_parameters"],
                     data["genesis_config_sha256"], data["created_at"])


def _account_key_bech32(b64_value: str) -> str:
    raw = b64_seed(b64_value, 33, "account_key_pair")  # flag || ed25519 seed
    return bech32_encode(IOTA_PRIVKEY_HRP, raw)


def prepare_committee(
    state_dir: Path,
    spec: CommitteeSpec,
    tools: ToolRunner,
    force: bool = False,
    now_ms: Optional[int] = None,
) -> Committee:
    """Step 1. Idempotent: reuses existing state when it matches ``spec``."""
    spec.validate()
    release = load_release()
    state_dir = Path(state_dir)
    state_dir.mkdir(parents=True, exist_ok=True)

    if (state_dir / COMMITTEE_JSON).exists() and not force:
        committee = load_committee(state_dir, release)
        if committee.spec != json.loads(json.dumps(spec.fingerprint())):
            raise CommitteeError(
                f"persisted committee at {state_dir} was prepared for a different topology",
                hint="expected spec=%s; found spec=%s. Use the same IPs/names, a new artifacts dir, or --force "
                "(which regenerates keys AND changes genesis.blob)" % (spec.fingerprint(), committee.spec),
            )
        age_ms = int(time.time() * 1000) - int(committee.genesis_parameters["chain_start_timestamp_ms"])
        if age_ms > int(committee.genesis_parameters["epoch_duration_ms"]):
            logger.warning(
                "reusing committee whose chain_start_timestamp_ms is %.1f h old (> one epoch); "
                "the first checkpoints will advance the epoch immediately", age_ms / 3.6e6,
            )
        logger.info("Step 1: reusing persisted committee in %s (%d validators, %d gateways)",
                    state_dir, len(committee.validators), len(committee.gateways))
        return committee

    if force:
        for leftover in (COMMITTEE_JSON, GENESIS_CONFIG, SECRETS_JSON, BENCHMARK_KEYSTORE):
            (state_dir / leftover).unlink(missing_ok=True) if hasattr(Path, "unlink") else None
        logger.warning("Step 1: --force: regenerating committee keys and genesis config in %s", state_dir)

    logger.info("Step 1: generating committee for '%s' with IOTA %s (%s)", spec.network_name, release.tag, tools.describe())
    with tempfile.TemporaryDirectory(prefix=".prepare-", dir=str(state_dir)) as tmp_name:
        tmp = Path(tmp_name)
        (tmp / "bench").mkdir()
        args = ["genesis", "--write-config", "cfg.yaml", "--working-dir", "bench",
                "--benchmark-ips", *[ip for _n, ip in spec.validators],
                "--committee-size", str(len(spec.validators))]
        if spec.epoch_duration_ms is not None:
            args += ["--epoch-duration-ms", str(spec.epoch_duration_ms)]
        out = tools.run_localnet(args, tmp)
        logger.debug("iota-localnet --write-config output:\n%s", out)
        cfg_path = tmp / "cfg.yaml"
        if not cfg_path.is_file():
            raise CommitteeError("iota-localnet did not write cfg.yaml", hint=f"output:\n{out[-800:]}")
        cfg = yaml.safe_load(cfg_path.read_text(encoding="utf-8"))
        infos = cfg.get("validator_config_info") or []
        if len(infos) != len(spec.validators):
            raise CommitteeError(f"builder returned {len(infos)} validators, expected {len(spec.validators)}")

        secrets: Dict[str, Dict[str, str]] = {}
        nodes: List[CommitteeNode] = []
        for index, ((name, ip), info) in enumerate(zip(spec.validators, infos)):
            ports = spec.ports_for(index)
            network_seed = b64_seed(info["network_key_pair"], 32, f"{name}.network_key_pair")
            protocol_seed = b64_seed(info["protocol_key_pair"], 32, f"{name}.protocol_key_pair")
            b64_seed(info["authority_key_pair"], 32, f"{name}.authority_key_pair")
            info.update(
                name=name,
                network_address=f"/ip4/{ip}/tcp/{ports.network}/http",
                p2p_address=f"/ip4/{ip}/udp/{ports.p2p}/quic",
                p2p_listen_address=f"0.0.0.0:{ports.p2p}",
                metrics_address=f"0.0.0.0:{ports.metrics}",
                admin_interface_address=f"127.0.0.1:{ports.admin}",
                primary_address=f"/ip4/{ip}/udp/{ports.consensus}/http",
            )
            secrets[name] = {
                "authority_key": info["authority_key_pair"],
                "protocol_key": iota_privkey_from_seed(protocol_seed),
                "account_key": _account_key_bech32(info["account_key_pair"]),
                "network_key": iota_privkey_from_seed(network_seed),
            }
            nodes.append(CommitteeNode(name, "validator", index, ip, ports.as_dict(),
                                       peer_id_from_network_seed(network_seed)))

        ssfn: List[Dict[str, Any]] = []
        for g_index, (name, ip) in enumerate(spec.gateways):
            index = len(spec.validators) + g_index
            ports = spec.ports_for(index)
            seed = new_seed()
            ssfn.append({"p2p_address": f"/ip4/{ip}/udp/{ports.p2p}/quic",
                         "network_key_pair": base64.b64encode(seed).decode()})
            secrets[name] = {"network_key": iota_privkey_from_seed(seed)}
            nodes.append(CommitteeNode(name, "gateway", index, ip, ports.as_dict(), peer_id_from_network_seed(seed)))
        cfg["ssfn_config_info"] = ssfn or None

        chain_start = int(now_ms if now_ms is not None else time.time() * 1000)
        cfg["parameters"]["chain_start_timestamp_ms"] = chain_start

        cfg_bytes = yaml.safe_dump(cfg, sort_keys=False).encode("utf-8")
        _write_secret(state_dir / GENESIS_CONFIG, cfg_bytes)
        _write_secret(state_dir / SECRETS_JSON, json.dumps(secrets, indent=2).encode("utf-8"))
        bench = tmp / "bench" / BENCHMARK_KEYSTORE
        if bench.is_file():
            _write_secret(state_dir / BENCHMARK_KEYSTORE, bench.read_bytes())

        committee = Committee(
            state_dir=state_dir,
            release=release.stamp(),
            spec=json.loads(json.dumps(spec.fingerprint())),
            nodes=nodes,
            genesis_parameters={
                "chain_start_timestamp_ms": chain_start,
                "epoch_duration_ms": int(cfg["parameters"]["epoch_duration_ms"]),
                "protocol_version": int(cfg["parameters"]["protocol_version"]),
            },
            genesis_config_sha256=_sha256_bytes(cfg_bytes),
            created_at=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        )

    if committee.genesis_parameters["protocol_version"] != release.protocol_version:
        raise CommitteeError(
            f"builder protocol_version {committee.genesis_parameters['protocol_version']} != pinned {release.protocol_version}",
            hint="the tools are not the pinned release",
        )
    (state_dir / COMMITTEE_JSON).write_text(json.dumps(committee.to_json(), indent=2) + "\n", encoding="utf-8")
    for node in committee.nodes:
        logger.info("  %-12s %-9s %-10s p2p=%s peer-id=%s…", node.name, node.role, node.ip, node.p2p_external(), node.peer_id[:12])
    logger.info("Step 1 done: committee state in %s (protocol v%s, epoch=%d ms)", state_dir,
                committee.genesis_parameters["protocol_version"], committee.genesis_parameters["epoch_duration_ms"])
    return committee
